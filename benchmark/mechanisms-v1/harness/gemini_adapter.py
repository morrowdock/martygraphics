def package_digest(package):
    """Canonical digest of every regular package file; no credentials/config."""
    records = []
    for path in sorted(Path(package).rglob("*")):
        if path.is_symlink() or not (path.is_file() or path.is_dir()):
            raise ValueError("Gemini package contains a link or special file")
        if path.is_file():
            records.append([path.relative_to(package).as_posix(), live.digest(path)])
    return hashlib.sha256(live.json_bytes(records)).hexdigest()


def auth_present(path):
    """Local structure only. Does not validate refreshability or account access."""
    path = Path(path)
    if path.is_symlink() or not path.is_file():
        return False
    if path.stat().st_mode & 0o077:
        raise ValueError("OAuth file must be private (mode 0600)")
    try:
        doc = json.loads(path.read_bytes())
        return isinstance(doc, dict) and isinstance(doc.get("refresh_token"), str) and bool(doc["refresh_token"]) and doc.get("type") in (None, "authorized_user")
    except (ValueError, OSError):
        return False


